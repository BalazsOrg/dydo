    [InlineData("test.md", "![Diagram](./assets/diagram.svg)", "assets/diagram.svg", "")]
    [InlineData("guides/doc.md", "![Diagram](./assets/missing.svg)", "guides/assets/diagram.svg", "Broken link: ./assets/missing.svg")]
    [InlineData("test.md", "[Asset](./diagram.svg)", "diagram.svg", "")]
    [InlineData("test.md", "[Asset](./image.png)", "image.png", "")]
    [InlineData("test.md", "[Asset](./photo.jpg)", "photo.jpg", "")]
    [InlineData("test.md", "[Asset](./photo.jpeg)", "photo.jpeg", "")]
    [InlineData("test.md", "[Asset](./animation.gif)", "animation.gif", "")]
    [InlineData("test.md", "[Asset](./modern.webp)", "modern.webp", "")]
    [InlineData("test.md", "[Asset](./favicon.ico)", "favicon.ico", "")]
    [InlineData("test.md", "[Asset](./document.pdf)", "document.pdf", "")]
    [InlineData("test.md", "[Asset](./archive.zip)", "archive.zip", "")]
    // a root-level sibling with an existing anchor, followed by another heading
    [InlineData("guide.md", "[Ref](./reference.md#section-1)", "reference.md", "", "# Section 1\n\n## Section 2")]
    public void Check_LinkFindings_AreExactlyTheOnesReported(
        string source, string links, string? existing, string expected, string targetHeadings = "# Section 1")
    {
        using var project = new DocsProject();
        // A page target's anchors are exactly its headings: by default ["section-1"].
        if (existing is not null)
            project.Write(existing, existing.EndsWith(".md") ? GuideWithoutAnchor + "\n" + targetHeadings + "\n\nText.\n" : "fixture");
        var frontmatter = source.StartsWith("project/decisions/")
            ? "---\narea: project\ntype: decision\nstatus: accepted\ndate: 2025-01-15\n---\n"
            : Guide;
        project.Write(source, frontmatter + Body + "\n" + links + "\n");

        var (code, output) = DydoCli.RunCombined("check");

        Assert.Equal(expected.Length == 0 ? [] : expected.Split('|'), Findings(output));
        Assert.True(code == (expected.Length == 0 ? 0 : 1), $"exit {code}:\n{output}");
    }

    [Fact]
    [Trait("Job", "trap: #0186 (an anchor-only link was reported with an empty target: one to a missing heading on its own page is reported exactly as `Broken link: #missing`, exit 1)")]
    public void Check_AnchorOnlyLink_ToAMissingHeadingOnItsPage_IsReportedOnce()
    {
        using var project = new DocsProject();
        // The page's anchors are exactly the rule case's: ["section"].
        project.Write("guide.md", GuideWithoutAnchor + "\n# Section\n\n[x](#missing)\n");

        var (code, output) = DydoCli.RunCombined("check");

        Assert.Equal(["Broken link: #missing"], Findings(output));
        Assert.True(code == 1, $"exit {code}:\n{output}");
    }

    [Theory]
    [Trait("Job", "trap: #0205 (a hub `dydo fix` generated failed check on the links it copied): dydo check skips the link checks of exactly the pages with a line that is the legacy marker")]
    // The rule cases' pages, byte for byte: a legacy hub with and without the marker line, and
    // prose quoting it. None has frontmatter or a title, so each also reports those two findings.
    [InlineData("project/generated/_index.md", LegacyMarker + "\n[x](#missing)", "Missing frontmatter|Missing title (# heading)")]
    [InlineData("project/generated/_index.md", "[x](#missing)", "Missing frontmatter|Missing title (# heading)|Broken link: #missing")]
    [InlineData("project/generated/guide.md", "The generated-file marker is `" + LegacyMarker + "`.\n[x](#missing)", "Missing frontmatter|Missing title (# heading)|Broken link: #missing")]
    public void Check_LegacyHubMarker_SkipsLinkChecksOnlyOnAMarkedPage(string path, string page, string expected)
    {
        using var project = new DocsProject();
        project.Write(path, page);

        var (code, output) = DydoCli.RunCombined("check");

        Assert.Equal(expected.Split('|'), Findings(output));
        Assert.True(code == 1, $"exit {code}:\n{output}");
    }

    // Each finding line `dydo check` prints, without its line number.
    private static IEnumerable<string> Findings(string output) =>
        Regex.Matches(output, @"^    - (?:Line \d+: )?(.*?)\r?$", RegexOptions.Multiline).Select(m => m.Groups[1].Value);

    [Fact]
    [Trait("Job", "contract: dydo-commands-core.md dydo check <path> (a <path> inside the docs tree scopes the report, exit 1 on its errors)")]
    public void Check_ScopedToAFolder_ResolvesLinksOutsideItButReportsOnlyInside()
    {
        using var project = new DocsProject();
        project.Write("guides/source.md", Guide + Body + "\n[Reference](../reference/target.md)\n[Missing](./missing.md)\n");
        project.Write("reference/target.md", "---\narea: reference\ntype: reference\n---\n\n# Target\n");
        project.Write("reference/broken.md", "---\narea: reference\ntype: reference\n---\n\n# Broken\n\n[Gone](./gone.md)\n");

        var (code, output) = DydoCli.RunCombined("check", Path.Combine("dydo", "guides"));

        Assert.Equal(1, code);
        Assert.Contains("Broken link: ./missing.md", output);
        Assert.DoesNotContain("target.md", output);
        Assert.DoesNotContain("gone.md", output);
    }
